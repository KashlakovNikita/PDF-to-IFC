"""Задача 28: типовые габариты узлов, измеренные по эталонной модели проекта.

Откуда числа
-------------
Из эталона `data/raw/ПРНС_ЛО_ТКР-ТС_У1_Э1_I2300.ifc`, измерено
`scripts/measure_reference_sizes.py` (тем же ifcopenshell.geom, что и сверка
геометрии). Для каждого типа объекта берётся медиана по всем его экземплярам:
единичный объект может быть нетиповым, медиана переживает выбросы.

Приоритет источников: сначала свойства эталона («Длина» / «Ширина» / «Высота»),
которые написал проектировщик, и только если их нет — обмер геометрии по
СОБСТВЕННЫМ осям объекта. По осям мира мерить нельзя: канал под углом 30° даёт
габаритный ящик 20.02 x 8.91 м вместо реальных 13.98 x 1.74 м.

Что это НЕ значит
------------------
Это типовые размеры конкретного проекта, а не справочник. Они годятся, чтобы
объект перестал быть невидимой точкой в вьюере и занимал правдоподобное место,
но не для расчётов и не для заказа. Как только габариты появятся в разобранной
спецификации, их нужно брать оттуда, а таблицу оставить запасным значением.

Ориентация
-----------
Здесь только размеры. Куда объект повёрнут, знает не таблица, а генератор: узел
стоит на трассе, поэтому короб разворачивается вдоль неё (см. ifc_export).
Класть футляр или канал поперёк трубы было бы хуже, чем не рисовать их вовсе.
"""

from __future__ import annotations

from typing import Dict, NamedTuple, Optional


class NodeSize(NamedTuple):
    """Габарит узла: длина вдоль трассы, ширина поперёк, высота, м."""

    length_m: float
    width_m: float
    height_m: float
    source: str
    samples: int


# node_type -> габарит. Названия типов эталона, по которым мерили, указаны в
# source вместе со способом измерения и числом объектов.
NODE_TYPE_SIZES: Dict[str, NodeSize] = {
    "valve": NodeSize(
        1.65, 0.49, 0.49,
        "эталон, «Трубопроводная арматура», обмер геометрии по собственным осям", 18,
    ),
    "casing": NodeSize(
        3.51, 0.63, 0.64,
        "эталон, «Футляр», обмер геометрии по собственным осям (Ø 0.63 м)", 10,
    ),
    "channel": NodeSize(
        21.00, 1.64, 1.00,
        "эталон, «Канал», свойства «Длина»/«Ширина»/«Высота»", 12,
    ),
    "connection_point": NodeSize(
        0.50, 0.50, 0.50,
        "эталон, «Точка подключения к внешним сетям», обмер геометрии", 11,
    ),
}


def size_for(node_type: str) -> Optional[NodeSize]:
    """Габарит для типа узла или None, если типовых размеров для него нет.

    None — это не «нулевой размер», а «неизвестно»: такие узлы остаются без
    формы, как и было до задачи 28. Камеры и опоры сюда намеренно не включены:
    в эталоне они есть, но их габариты завязаны на конкретный типовой узел
    прокладки, и подставлять медиану по трём камерам как «типовой размер»
    значило бы выдать случайное число за проектное решение.
    """
    return NODE_TYPE_SIZES.get(node_type)
